"""Start Driver Threads and Consume Messages"""

import pika
import json
import threading
import time

# Driver binding patterns
driver_bindings = {
    "Ravi": "bangalore.koramangala.*",
    "Priya": "bangalore.indiranagar.*",
    "Arjun": "bangalore.*.ride",
    "Meena": "bangalore.*.food",
    "Karthik": "chennai.tnagar.food",
    "Control": "bangalore.#"
}

def start_driver(driver_name, binding_pattern):

    try:
        connection = pika.BlockingConnection(
            pika.URLParameters(AMQP_URL)
        )

        channel = connection.channel()

        # Use existing topic exchange
        channel.exchange_declare(
            exchange="zomato_exchange",
            exchange_type="topic",
            passive=True
        )

        # Create driver queue
        channel.queue_declare(queue=driver_name)

        # Bind queue to exchange
        channel.queue_bind(
            exchange="zomato_exchange",
            queue=driver_name,
            routing_key=binding_pattern
        )

        channel.basic_qos(prefetch_count=1)

        def callback(ch, method, properties, body):
            try:
                message = json.loads(body.decode())

                print(f"\n[{driver_name}] Received:")
                print(json.dumps(message, indent=2))

                ch.basic_ack(delivery_tag=method.delivery_tag)

            except Exception as e:
                print(f"[{driver_name}] Error:", e)
                ch.basic_nack(
                    delivery_tag=method.delivery_tag,
                    requeue=False
                )

        channel.basic_consume(
            queue=driver_name,
            on_message_callback=callback
        )

        print(f"{driver_name} is waiting for messages...")

        channel.start_consuming()

    except Exception as e:
        print(f"{driver_name} connection error:", e)


# Start all six drivers independently
for driver, pattern in driver_bindings.items():

    thread = threading.Thread(
        target=start_driver,
        args=(driver, pattern),
        daemon=True
    )

    thread.start()

    time.sleep(0.2)

print("\nAll driver threads started!")

