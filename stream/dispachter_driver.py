"""### D3: ACK and NACK Implementation"""

import json

def callback(ch, method, properties, body):

    try:
        # Convert message into JSON
        message = json.loads(body)

        # Validate message
        required_fields = ["id", "city", "zone", "type", "ts"]

        if not all(field in message for field in required_fields):
            raise ValueError("Missing required fields")

        # Process message
        print("\nMessage Received:")
        print(json.dumps(message, indent=4))

        print("Processing successful!")

        # ACK: Confirm successful processing
        ch.basic_ack(
            delivery_tag=method.delivery_tag
        )

        print("ACK sent successfully!")

    except Exception as e:

        print("Processing failed:", e)

        # NACK: Reject failed message
        ch.basic_nack(
            delivery_tag=method.delivery_tag,
            requeue=False
        )

        print("NACK sent successfully!")

