"""### 5. C2 — Test-gate experiment for `max_depth = 1, 2, 3, 4, 5`

"""

import pandas as pd
from pathlib import Path
import subprocess, re, json, os

prediction_file = REPO_DIR / "iris_predictions.csv"
c2_rows = []

for depth in [1, 2, 3, 4, 5]:
    if prediction_file.exists():
        prediction_file.unlink()

    runtime_json = json.dumps({"max_depth": depth})
    cmd = [
        "mage", "run", "iris_project", "iris_classifier",
        "--runtime-vars", runtime_json, "--test"
    ]
    print("\n" + "="*75)
    print("$", " ".join(cmd))
    result = subprocess.run(
        cmd, cwd=str(REPO_DIR), text=True,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT
    )
    output = result.stdout or ""
    print(output)

    accuracy_matches = re.findall(r"TEST_ACCURACY=([0-9]*\.?[0-9]+)", output)
    accuracy = float(accuracy_matches[-1]) if accuracy_matches else None
    gate_passed = "TEST_GATE_PASS" in output
    gate_failed = "TEST_GATE_FAIL" in output
    csv_created = prediction_file.exists()

    c2_rows.append({
        "max_depth": depth,
        "test_accuracy": accuracy,
        "test_accuracy passed?": gate_passed and not gate_failed,
        "iris_predictions.csv created?": csv_created,
        "mage_exit_code": result.returncode,
    })

c2_results = pd.DataFrame(c2_rows)
display(c2_results)

